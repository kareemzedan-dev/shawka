import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

val localProperties = Properties()
val localPropertiesFile = rootProject.file("local.properties")
if (localPropertiesFile.exists()) {
    localPropertiesFile.inputStream().use { localProperties.load(it) }
}

fun resolveGoogleMapsApiKey(): String {
    localProperties.getProperty("google.maps.apiKey")?.trim()?.let { if (it.isNotEmpty()) return it }
    val secretsFile = rootProject.file("../secrets.properties")
    if (secretsFile.exists()) {
        val secrets = Properties()
        secretsFile.inputStream().use { secrets.load(it) }
        secrets.getProperty("google.maps.apiKey")?.trim()?.let { if (it.isNotEmpty()) return it }
    }
    System.getenv("GOOGLE_MAPS_API_KEY")?.trim()?.let { if (it.isNotEmpty()) return it }
    return ""
}

val googleMapsApiKey = resolveGoogleMapsApiKey()

val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

